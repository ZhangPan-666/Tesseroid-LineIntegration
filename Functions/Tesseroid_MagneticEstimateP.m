function [V,...
    Vx,Vy,Vz,...
    Vxx,Vxy,Vyy,Vzx,Vzy,Vzz]...
    =Tesseroid_MagneticEstimateP(TesseroidParameters,PointParameters,AT,RT)
%TESSEROID_MAGNETICESTIMATEP Line-integral tesseroid magnetic field, OpenMP.
%   This has the same interface and output order as
%   Tesseroid_MagneticEstimateP in Tesseroid/Functions. Parallelism is native
%   OpenMP over observation points and does not require a MATLAB parpool.

[V,...
    Vx,Vy,Vz,...
    Vxx,Vxy,Vyy,Vzx,Vzy,Vzz] = ...
    tli_lineintegration_mex('magnetic',TesseroidParameters,PointParameters,AT,RT,true);
end
