function [V,...
    Vx,Vy,Vz,...
    Vxx,Vxy,Vyy,Vzx,Vzy,Vzz,...
    Vxxx,Vxxy,Vxxz,Vxyz,Vyyx,Vyyy,Vyyz,Vzzx,Vzzy,Vzzz]...
    =Tesseroid_GravityEstimateP(TesseroidParameters,PointParameters,AT,RT)
%TESSEROID_GRAVITYESTIMATEP Line-integral tesseroid gravity, OpenMP mode.
%   This has the same interface and output order as
%   Tesseroid_GravityEstimateP in Tesseroid/Functions. Parallelism is native
%   OpenMP over observation points and does not require a MATLAB parpool.

[V,...
    Vx,Vy,Vz,...
    Vxx,Vxy,Vyy,Vzx,Vzy,Vzz,...
    Vxxx,Vxxy,Vxxz,Vxyz,Vyyx,Vyyy,Vyyz,Vzzx,Vzzy,Vzzz] = ...
    tli_lineintegration_mex('gravity',TesseroidParameters,PointParameters,AT,RT,true);
end
