function [V,...
    Vx,Vy,Vz,...
    Vxx,Vxy,Vyy,Vzx,Vzy,Vzz]...
    =Tesseroid_MagneticEstimate(TesseroidParameters,PointParameters,AT,RT)
%TESSEROID_MAGNETICESTIMATE Line-integral tesseroid magnetic field, serial.
%   The calling interface and output order match Tesseroid_MagneticEstimate
%   in Tesseroid/Functions. TesseroidParameters is N-by-9:
%   [lat1 lat2 lon1 lon2 r1 r2 Mx My Mz], using the magnetization-coordinate
%   convention implemented by C++Codes/_TLI_estimate.h.
%   PointParameters is M-by-3: [latitude longitude radius].

[V,...
    Vx,Vy,Vz,...
    Vxx,Vxy,Vyy,Vzx,Vzy,Vzz] = ...
    tli_lineintegration_mex('magnetic',TesseroidParameters,PointParameters,AT,RT,false);
end
