function [V,...
    Vx,Vy,Vz,...
    Vxx,Vxy,Vyy,Vzx,Vzy,Vzz,...
    Vxxx,Vxxy,Vxxz,Vxyz,Vyyx,Vyyy,Vyyz,Vzzx,Vzzy,Vzzz]...
    =Tesseroid_GravityEstimate(TesseroidParameters,PointParameters,AT,RT)
%TESSEROID_GRAVITYESTIMATE Line-integral tesseroid gravity, serial mode.
%   The calling interface and output order match Tesseroid_GravityEstimate
%   in Tesseroid/Functions. Angles are degrees and radii use one consistent
%   length unit. TesseroidParameters is N-by-7:
%   [lat1 lat2 lon1 lon2 r1 r2 density].
%   PointParameters is M-by-3: [latitude longitude radius].

[V,...
    Vx,Vy,Vz,...
    Vxx,Vxy,Vyy,Vzx,Vzy,Vzz,...
    Vxxx,Vxxy,Vxxz,Vxyz,Vyyx,Vyyy,Vyyz,Vzzx,Vzzy,Vzzz] = ...
    tli_lineintegration_mex('gravity',TesseroidParameters,PointParameters,AT,RT,false);
end
